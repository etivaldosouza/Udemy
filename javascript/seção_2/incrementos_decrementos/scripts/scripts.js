/*
    Operadores de Incremento e Decremento:

*/ 

//incremento

var a = 1
a = a + 1 //alterei o valor de a incrementando 1
console.log(a)
a++         // outra maneira de incrementar 1
console.log(a)


/*
    diferença entre a++ e ++a

=> a++ você primeiro incrementa depois imprime

*/ 

a = 1
console.log(a++) // primeiro printa o valor de a (1) depois incrementa(1+1 = 2) e para vizualizar o novo valor incrementado tem q dá outro console.log(a)

console.log(a) //vai mostrar 2



/*
    com o ++a => ja mostra o valor incrementado)
*/

var a = 2
console.log(++a)


//com decremento:

var a = 1
console.log(a--)

console.log(a)


var a = 1
console.log(--a)