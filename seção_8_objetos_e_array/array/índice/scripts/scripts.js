/*
    Mais sobre arrays

=> Podemos acessar um array pelo seu índice, por exemplo: arr[1]

=> lembrando que o primeiro índice é o 0, ou seja, para acessar o primeiro elemento: arr[0]


*/ 


let arr = [1,4,5,6,7]

let nomes = ['Matheus','João','Aléxia']

let bool = [true,false,true]

console.log(arr[1])

console.log(nomes[0])

console.log(bool[1])

console.log(arr[arr.length - 1]) // para acessar o último elemento do array

console.log(nomes[nomes.length - 1])