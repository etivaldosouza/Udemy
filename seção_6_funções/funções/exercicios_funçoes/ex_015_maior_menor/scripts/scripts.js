/*
    Maior Número:

=> Crie uma função chamada maior que recebe dois números.

=> Retorne o maior deles.

=> Crie uma variável resultado que receba o retorno da função passando 20 e 35 como argumentos.

=> Mostre o resultado no console.


*/ 

function maiorNumero(n1,n2){
    return Math.max(n1,n2)
}

let resultado = maiorNumero(20,35)

console.log(resultado)