/*  Strings: 

   - a \ pode da um escape na string, e isso permite efeitos especiais;
   - por exemplo: \n pula uma linha
   - o temlplate literal(``) é usado quando queremos utilizar variáveis no meio de uma string
   - concatenar é um processo de somar strings ex: console.log("salada" + "de" + "frutas") 

*/

console.log('Essa é uma string \nde duas linhas')


// o template literal(uso de aspas) serve também para computar valores, ex:
console.log(`a soma de 2+2 é ${2+2}`)
